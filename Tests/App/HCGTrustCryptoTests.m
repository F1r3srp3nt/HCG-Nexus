@implementation HCGTrustCryptoTests

- (NSDate *)now { return [NSDate dateWithTimeIntervalSince1970:1795632000]; } // 2026-11-25

- (void)testPlatformImplementationsAreInUse {
    XCTAssertEqualObjects(HCGDigestImplementationName(), @"CommonCrypto");
    XCTAssertTrue([HCGOpenPGPImplementationName() containsString:@"Security framework"]);
}

- (void)testDigestsMatchThePortableImplementation {
    NSArray *inputs = @[ [NSData data], [@"abc" dataUsingEncoding:NSUTF8StringEncoding], Fixture(@"Release"), Fixture(@"founder-test.asc") ];
    for (NSData *input in inputs) {
        for (NSNumber *a in @[ @(HCGDigestAlgorithmSHA1), @(HCGDigestAlgorithmSHA256), @(HCGDigestAlgorithmSHA512) ]) {
            HCGDigestAlgorithm alg = (HCGDigestAlgorithm)a.integerValue;
            XCTAssertEqualObjects([HCGDigest digestOfData:input algorithm:alg], HCGPortableDigest(input, alg));
        }
    }
    XCTAssertEqualObjects([HCGDigest hexDigestOfData:[@"abc" dataUsingEncoding:NSUTF8StringEncoding] algorithm:HCGDigestAlgorithmSHA256],
                          @"ba7816bf8f01cfea414140de5dae2223b00361a396177a9cb410ff61f20015ad");
}

- (void)testSignatureVerdictsMatchGpgv {
    NSString *error = nil;
    HCGPGPCertificate *cert = [HCGPGPCertificate certificateWithData:Fixture(@"founder-test.asc") error:&error];
    XCTAssertNotNil(cert, @"%@", error);
    NSString *fpr = [[[NSString alloc] initWithData:Fixture(@"founder-test.fpr") encoding:NSUTF8StringEncoding]
                     stringByTrimmingCharactersInSet:[NSCharacterSet whitespaceAndNewlineCharacterSet]];
    XCTAssertEqualObjects(cert.primary.fingerprint, fpr);
    XCTAssertTrue(cert.subkeys.firstObject.canSign, @"binding and back-signature verified by the Security framework");
    NSData *release = Fixture(@"Release");
    XCTAssertEqual([HCGOpenPGP verifyDetachedSignature:Fixture(@"Release.gpg") data:release certificate:cert now:self.now].status, HCGPGPStatusGood);
    XCTAssertEqual([HCGOpenPGP verifyDetachedSignature:Fixture(@"Release.sha256.sig") data:release certificate:cert now:self.now].status, HCGPGPStatusGood);
    XCTAssertEqual([HCGOpenPGP verifyDetachedSignature:Fixture(@"Release.gpg") data:Fixture(@"Release.tampered") certificate:cert now:self.now].status, HCGPGPStatusBad);
    XCTAssertEqual([HCGOpenPGP verifyDetachedSignature:Fixture(@"Release.sha1.asc") data:release certificate:cert now:self.now].status, HCGPGPStatusWeakDigest);
    XCTAssertEqual([HCGOpenPGP verifyDetachedSignature:Fixture(@"Release.other.asc") data:release certificate:cert now:self.now].status, HCGPGPStatusUnknownSigner);
    HCGPGPVerification *inl = [HCGOpenPGP verifyCleartextMessage:Fixture(@"InRelease") certificate:cert now:self.now];
    XCTAssertEqual(inl.status, HCGPGPStatusGood);
    XCTAssertEqualObjects(inl.signedText, release);
    XCTAssertEqual([HCGOpenPGP verifyCleartextMessage:Fixture(@"InRelease.tampered") certificate:cert now:self.now].status, HCGPGPStatusBad);
    HCGPGPCertificate *expired = [HCGPGPCertificate certificateWithData:Fixture(@"expired-test.asc") error:NULL];
    XCTAssertEqual([HCGOpenPGP verifyDetachedSignature:Fixture(@"Release.expired.asc") data:release certificate:expired now:self.now].status, HCGPGPStatusKeyExpired);
    HCGPGPCertificate *other = [HCGPGPCertificate certificateWithData:Fixture(@"other-test.asc") error:NULL];
    XCTAssertEqual([HCGOpenPGP verifyDetachedSignature:Fixture(@"Release.other.asc") data:release certificate:other now:self.now].status, HCGPGPStatusGood);
}

- (void)testPlatformAndPortableRSAAgree {
    HCGPGPCertificate *cert = [HCGPGPCertificate certificateWithData:Fixture(@"founder-test.asc") error:NULL];
    HCGPGPKey *sub = cert.subkeys.firstObject;
    // A digest the key did not sign: both implementations refuse; a flipped modulus byte as well.
    NSData *digest = [HCGDigest digestOfData:Fixture(@"Release") algorithm:HCGDigestAlgorithmSHA512];
    NSMutableData *sig = [NSMutableData dataWithLength:sub.modulus.length];
    ((uint8_t *)sig.mutableBytes)[sig.length - 1] = 7;
    XCTAssertFalse(HCGPortableRSAVerify(sub.modulus, sub.exponent, sig, HCGDigestAlgorithmSHA512, digest));
}

