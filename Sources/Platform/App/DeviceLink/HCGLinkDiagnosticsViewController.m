#import "HCGLinkDiagnosticsViewController.h"
#import "HCGTheme.h"

@implementation HCGLinkDiagnosticsViewController

- (instancetype)initWithContext:(HCGPanelContext *)context diagnostics:(HCGLinkDiagnosticsInfo *)diagnostics {
    if ((self = [super initWithContext:context])) {
        _diagnostics = diagnostics;
    }
    return self;
}

+ (NSString *)headerTextForDiagnostics:(HCGLinkDiagnosticsInfo *)diagnostics {
    NSString *text = [NSString stringWithFormat:@"%@ — read-only diagnostics", diagnostics.serverName];
    return diagnostics.localDevelopment ? [NSString stringWithFormat:@"%@\n%@", text, HCGLinkLocalDevelopmentLabel] : text;
}

- (void)viewDidLoad {
    [super viewDidLoad];
    self.title = @"Diagnostics";
    self.tableView.allowsSelection = NO;
}

- (NSInteger)numberOfSectionsInTableView:(UITableView *)tableView {
    return 1 + (NSInteger)self.diagnostics.sections.count;
}

- (NSString *)tableView:(UITableView *)tableView titleForHeaderInSection:(NSInteger)section {
    if (section == 0) return @"HCG Server";
    return self.diagnostics.sections[(NSUInteger)section - 1].title;
}

- (NSString *)tableView:(UITableView *)tableView titleForFooterInSection:(NSInteger)section {
    if (section != 0) return nil;
    return @"HCG Server redacts these diagnostics before sending them (no logs, addresses or credentials). Nexus shows them as plain text and changes nothing on the server.";
}

- (NSInteger)tableView:(UITableView *)tableView numberOfRowsInSection:(NSInteger)section {
    if (section == 0) return 1;
    return MAX(1, (NSInteger)self.diagnostics.sections[(NSUInteger)section - 1].lines.count);
}

- (UITableViewCell *)tableView:(UITableView *)tableView cellForRowAtIndexPath:(NSIndexPath *)indexPath {
    if (indexPath.section == 0) {
        UITableViewCell *cell = [self styledCellWithStyle:UITableViewCellStyleSubtitle identifier:@"diagnostics-header"];
        cell.selectionStyle = UITableViewCellSelectionStyleNone;
        cell.textLabel.text = [HCGLinkDiagnosticsViewController headerTextForDiagnostics:self.diagnostics];
        cell.textLabel.numberOfLines = 0;
        cell.textLabel.font = [HCGTheme fontForTextStyle:UIFontTextStyleHeadline weight:UIFontWeightSemibold];
        NSDateFormatter *formatter = [[NSDateFormatter alloc] init];
        formatter.dateStyle = NSDateFormatterMediumStyle;
        formatter.timeStyle = NSDateFormatterMediumStyle;
        cell.detailTextLabel.text = [NSString stringWithFormat:@"Generated by the server %@", [formatter stringFromDate:self.diagnostics.generatedAt]];
        cell.imageView.image = [HCGTheme symbolNamed:@"stethoscope" pointSize:17];
        return cell;
    }
    // Plain UILabel text only: labels never detect or open links.
    UITableViewCell *cell = [self styledCellWithStyle:UITableViewCellStyleDefault identifier:@"diagnostics-line"];
    cell.selectionStyle = UITableViewCellSelectionStyleNone;
    cell.textLabel.numberOfLines = 0;
    cell.textLabel.font = [HCGTheme fontForTextStyle:UIFontTextStyleCallout weight:UIFontWeightRegular];
    NSArray<NSString *> *lines = self.diagnostics.sections[(NSUInteger)indexPath.section - 1].lines;
    cell.textLabel.text = lines.count ? lines[(NSUInteger)indexPath.row] : @"(none)";
    cell.textLabel.textColor = lines.count ? [HCGTheme primaryText] : [HCGTheme secondaryText];
    return cell;
}

@end
