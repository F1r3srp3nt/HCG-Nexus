#!/usr/bin/env python3
"""Embeds Resources/Registry/hcg-ecosystem-registry.json into Sources/Core/HCGRegistryData.m.

The JSON file is the source of truth for HCG Nexus's ecosystem registry (docs/COMMAND-CENTER.md); the generated file
lets the tweak, the Settings bundle, the app and the host tests read the same data without a resource path.

  scripts/embed_registry.py          regenerate
  scripts/embed_registry.py --check  fail when the generated file is out of date (scripts/check.sh)
"""
import json, os, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "Resources/Registry/hcg-ecosystem-registry.json")
OUT = os.path.join(ROOT, "Sources/Core/HCGRegistryData.m")

def render():
    data = json.load(open(SRC, encoding="utf-8"))
    assert data.get("schema") == "hcg.nexus.registry/1", "schema"
    text = json.dumps(data, ensure_ascii=False, separators=(",", ":"), sort_keys=False).encode("utf-8")
    lines, cur = [], ""
    for b in text:
        c = chr(b)
        if b < 0x20 or b >= 0x7F: piece = "\\%03o" % b
        elif c == '"': piece = '\\"'
        elif c == "\\": piece = "\\\\"
        elif c == "?": piece = "\\?"  # no trigraphs
        else: piece = c
        cur += piece
        if len(cur) > 100 and c == ",":
            lines.append('    "%s"' % cur); cur = ""
    if cur: lines.append('    "%s"' % cur)
    return ("// GENERATED by scripts/embed_registry.py from Resources/Registry/hcg-ecosystem-registry.json. Do not edit.\n"
            "#import \"HCGRegistry.h\"\n\n"
            "static const char kHCGRegistryJSON[] =\n" + "\n".join(lines) + ";\n\n"
            "NSString *HCGRegistryBuiltInJSON(void) {\n"
            "    return [NSString stringWithUTF8String:kHCGRegistryJSON];\n"
            "}\n")

out = render()
if "--check" in sys.argv:
    cur = open(OUT, encoding="utf-8").read() if os.path.exists(OUT) else ""
    if cur != out:
        sys.exit("Sources/Core/HCGRegistryData.m is out of date: run scripts/embed_registry.py")
    print("registry embedded and up to date")
else:
    open(OUT, "w", encoding="utf-8").write(out)
    print("wrote", os.path.relpath(OUT, ROOT))
